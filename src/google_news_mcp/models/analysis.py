from typing import Any

from pydantic import BaseModel, Field

from google_news_mcp.models.article import NewsArticle


class ToolCallRecord(BaseModel):
    """One Google News tool call that Gemini decided to make."""

    name: str = Field(description="Name of the MCP tool Gemini called.")
    arguments: dict[str, Any] = Field(description="Arguments Gemini passed to the tool.")
    article_count: int = Field(default=0, description="Number of articles the call returned.")
    error: str | None = Field(default=None, description="Error message if the call failed.")


class NewsAnalysisResponse(BaseModel):
    """Gemini's answer to a news question, grounded in Google News results."""

    question: str = Field(description="The user's original question.")
    model: str = Field(description="Gemini model that produced the briefing.")
    briefing: str = Field(description="Gemini's briefing, based only on the retrieved articles.")
    tool_calls: list[ToolCallRecord] = Field(
        description="Google News tools Gemini called, in order."
    )
    count: int = Field(description="Number of unique articles retrieved.")
    articles: list[NewsArticle] = Field(
        description="Articles exactly as returned by Google News (not generated by Gemini)."
    )
