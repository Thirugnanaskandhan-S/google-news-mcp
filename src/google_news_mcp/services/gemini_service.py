"""Gemini-powered news analysis.

Gemini receives the server's own Google News tool definitions, decides which
tools to call, and writes a briefing. The articles returned to the caller are
the original Google News results collected from those tool calls, never text
generated by Gemini, so headlines, publishers, dates and URLs cannot be invented.
"""

import logging
import os
from collections.abc import Awaitable, Callable, Sequence
from typing import Any, Protocol

from pydantic import ValidationError

from google_news_mcp.config import settings
from google_news_mcp.models.analysis import NewsAnalysisResponse, ToolCallRecord
from google_news_mcp.models.article import NewsArticle

logger = logging.getLogger(__name__)

NEWS_TOOL_NAMES: tuple[str, ...] = (
    "search_news",
    "get_top_headlines",
    "search_news_by_publisher",
)

SYSTEM_INSTRUCTION = """\
You are a news research assistant connected to Google News through tools.

How to use the tools:
- Always use the tools to find articles before answering. Never invent headlines, \
publishers, dates or URLs.
- Use search_news_by_publisher when the user names a publisher, passing its domain \
(for example bbc.com or reuters.com). Use get_top_headlines for general "what is \
happening" questions. Use search_news for topic searches.
- Keep tool queries to a few keywords rather than the whole question.
- Unless the user names a country or language, keep the tools' default region and \
language.
- If a search returns no useful articles, you may try one different query.

How to answer:
- Write a briefing of 3 to 5 short bullet points in plain text, each starting with "- ".
- Do not use Markdown headings, bold text or links.
- Base every point only on the retrieved articles, and name the publisher when you \
refer to a specific report.
- If no relevant articles were found, say so in one sentence.
"""

ProgressCallback = Callable[[str], Awaitable[None]]


class ToolRunner(Protocol):
    """What the analyst needs from an MCP server. `MCPServer` satisfies this."""

    async def list_tools(self) -> Sequence[Any]: ...

    async def call_tool(self, name: str, arguments: dict[str, Any]) -> Any: ...


class GeminiConfigurationError(RuntimeError):
    """Gemini cannot run: missing API key or missing `google-genai` package."""


class GeminiNewsAnalyst:
    """Answer news questions by letting Gemini orchestrate the Google News tools."""

    def __init__(
        self,
        tool_runner: ToolRunner,
        *,
        tool_names: Sequence[str] = NEWS_TOOL_NAMES,
        max_tool_rounds: int = settings.gemini_max_tool_rounds,
        max_articles: int = settings.gemini_max_articles,
    ) -> None:
        self._tool_runner = tool_runner
        self._tool_names = tuple(tool_names)
        self._max_tool_rounds = max_tool_rounds
        self._max_articles = max_articles

    async def analyze(
        self,
        question: str,
        *,
        on_progress: ProgressCallback | None = None,
    ) -> NewsAnalysisResponse:
        """Run the Gemini tool-calling loop and return a grounded briefing.

        Raises:
            GeminiConfigurationError: If the API key or the Gemini SDK is missing.
        """
        question = question.strip()
        api_key = os.getenv("GEMINI_API_KEY")
        if not api_key:
            raise GeminiConfigurationError(
                "GEMINI_API_KEY is not set. Add it to the .env file in the project "
                "root and restart the server."
            )
        model = os.getenv("GEMINI_MODEL") or settings.gemini_model

        try:
            from google import genai
            from google.genai import types
        except ImportError as error:
            raise GeminiConfigurationError(
                'The google-genai package is not installed. Run: pip install -e ".[ai]"'
            ) from error

        async def progress(message: str) -> None:
            logger.info(message)
            if on_progress is not None:
                try:
                    await on_progress(message)
                except Exception:  # Progress reporting must never break the analysis.
                    logger.debug("Progress callback failed", exc_info=True)

        gemini_tools = await self._gemini_tools(types)
        tool_calls: list[ToolCallRecord] = []
        articles: dict[str, dict[str, Any]] = {}

        def config(mode: str) -> Any:
            return types.GenerateContentConfig(
                system_instruction=SYSTEM_INSTRUCTION,
                tools=gemini_tools,
                temperature=0.2,
                tool_config=types.ToolConfig(
                    function_calling_config=types.FunctionCallingConfig(mode=mode)
                ),
            )

        http_options = types.HttpOptions(timeout=settings.gemini_timeout_ms)
        async with genai.Client(api_key=api_key, http_options=http_options).aio as client:
            conversation = [
                types.Content(role="user", parts=[types.Part.from_text(text=question)])
            ]

            await progress(f"Asking Gemini ({model}) to plan the search...")
            # "ANY" forces a tool call first, so every briefing is grounded in results.
            response = await client.models.generate_content(
                model=model, contents=conversation, config=config("ANY")
            )

            tool_round = 0
            while response.function_calls:
                if tool_round >= self._max_tool_rounds:
                    await progress("Tool-call limit reached; asking Gemini to summarise.")
                    response = await client.models.generate_content(
                        model=model, contents=conversation, config=config("NONE")
                    )
                    break

                tool_round += 1
                if not response.candidates or response.candidates[0].content is None:
                    raise RuntimeError("Gemini returned an empty response.")

                # Keep Gemini's function-call turn (including any thought signatures).
                conversation.append(response.candidates[0].content)

                response_parts = []
                for function_call in response.function_calls:
                    name = function_call.name or ""
                    arguments = dict(function_call.args or {})
                    await progress(f"Gemini selected {name} with {arguments}")

                    result_data, record = await self._run_tool(name, arguments, articles)
                    tool_calls.append(record)
                    await progress(
                        f"{name} failed: {record.error}"
                        if record.error
                        else f"{name} returned {record.article_count} articles"
                    )

                    response_parts.append(
                        types.Part(
                            function_response=types.FunctionResponse(
                                name=name, response=result_data, id=function_call.id
                            )
                        )
                    )

                # The Gemini API rejects role="tool"; function responses go in a user turn.
                conversation.append(types.Content(role="user", parts=response_parts))

                await progress("Gemini is reviewing the results...")
                response = await client.models.generate_content(
                    model=model, contents=conversation, config=config("AUTO")
                )

        briefing = (response.text or "").replace("**", "").strip()
        article_models = self._to_article_models(articles.values())

        return NewsAnalysisResponse(
            question=question,
            model=model,
            briefing=briefing or "Gemini did not return a briefing.",
            tool_calls=tool_calls,
            count=len(article_models),
            articles=article_models,
        )

    async def _gemini_tools(self, types: Any) -> list[Any]:
        """Convert the allowed MCP tool definitions into Gemini declarations."""
        declarations = [
            types.FunctionDeclaration(
                name=tool.name,
                description=tool.description or tool.name,
                parameters_json_schema=tool.input_schema,
            )
            for tool in await self._tool_runner.list_tools()
            if tool.name in self._tool_names
        ]
        if not declarations:
            raise RuntimeError("None of the Google News tools are registered on the server.")
        return [types.Tool(function_declarations=declarations)]

    async def _run_tool(
        self,
        name: str,
        arguments: dict[str, Any],
        articles: dict[str, dict[str, Any]],
    ) -> tuple[dict[str, Any], ToolCallRecord]:
        """Execute one tool call, collecting any articles it returns.

        Errors are returned to Gemini as data (so it can adjust and retry) rather
        than raised.
        """
        if name not in self._tool_names:
            error = f"Unknown tool {name!r}. Available tools: {', '.join(self._tool_names)}."
            return {"error": error}, ToolCallRecord(name=name, arguments=arguments, error=error)

        try:
            result = await self._tool_runner.call_tool(name, arguments)
        except Exception as error:
            logger.warning("Tool %s failed for Gemini", name, exc_info=True)
            message = str(error) or type(error).__name__
            return {"error": message}, ToolCallRecord(
                name=name, arguments=arguments, error=message
            )

        data = getattr(result, "structured_content", None)
        if not isinstance(data, dict):
            texts = [item.text for item in getattr(result, "content", []) if hasattr(item, "text")]
            data = {"content": texts}

        if getattr(result, "is_error", False):
            message = "; ".join(data.get("content", [])) or "Tool call failed."
            return {"error": message}, ToolCallRecord(
                name=name, arguments=arguments, error=message
            )

        found = data.get("articles") or []
        for article in found:
            url = article.get("url") if isinstance(article, dict) else None
            if url:
                articles.setdefault(url, article)

        return data, ToolCallRecord(name=name, arguments=arguments, article_count=len(found))

    def _to_article_models(self, raw_articles: Any) -> list[NewsArticle]:
        """Validate the collected article dicts, skipping malformed ones."""
        models: list[NewsArticle] = []
        for raw in raw_articles:
            if len(models) >= self._max_articles:
                break
            try:
                models.append(NewsArticle.model_validate(raw))
            except ValidationError:
                logger.debug("Skipping malformed article: %r", raw)
        return models
